"""Schema creation, versioning and lightweight migrations.

The ORM models are the source of truth; ``create_all`` builds a fresh database.
For an existing database we run an ordered list of migration steps, tracked by
a version number in the ``kv`` table.

Why not Alembic out of the box? Because for a single-operator media pipeline,
the failure mode that matters is "I upgraded and my library still opens". A
short, explicit, hand-reviewed list of steps that runs automatically on start
is easier to reason about than autogenerated revisions. Alembic is still an
option -- the models are plain SQLAlchemy and ``pip install
'broadcastbrain[postgres]'`` pulls it in for anyone who wants it.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import Callable, Optional

from sqlalchemy import inspect, select, text
from sqlalchemy.orm import Session

from ..errors import DatabaseError
from .base import Database
from .models import Base, KeyValue

log = logging.getLogger(__name__)

#: Bump when a migration step is appended below.
SCHEMA_VERSION = 1
SCHEMA_VERSION_KEY = "schema_version"


@dataclass(frozen=True)
class Migration:
    """One forward step. ``apply`` receives an open session."""

    version: int
    description: str
    apply: Callable[[Session, Database], None]


#: Ordered forward migrations. Append only; never edit a released entry.
MIGRATIONS: tuple[Migration, ...] = ()


def initialize(db: Database, *, create_fts: bool = True) -> int:
    """Create or upgrade the schema. Safe to call on every start.

    Returns:
        The schema version now in effect.
    """
    inspector = inspect(db.engine)
    existed = "clips" in inspector.get_table_names()

    Base.metadata.create_all(db.engine)

    with db.write_session() as session:
        current = _read_version(session)
        if current is None:
            # Fresh database (or one created before versioning existed).
            current = SCHEMA_VERSION if not existed else 0
            _write_version(session, current)

        if current > SCHEMA_VERSION:
            raise DatabaseError(
                f"database schema version {current} is newer than this build "
                f"supports ({SCHEMA_VERSION}). Upgrade BroadcastBrain."
            )

        for migration in MIGRATIONS:
            if migration.version <= current:
                continue
            log.info("applying migration %s: %s", migration.version, migration.description)
            migration.apply(session, db)
            current = migration.version
            _write_version(session, current)

    if create_fts and db.is_sqlite:
        ensure_fts(db)
    return current


def _read_version(session: Session) -> Optional[int]:
    row = session.get(KeyValue, SCHEMA_VERSION_KEY)
    if row is None or not isinstance(row.value, dict):
        return None
    value = row.value.get("version")
    return int(value) if isinstance(value, (int, float, str)) else None


def _write_version(session: Session, version: int) -> None:
    row = session.get(KeyValue, SCHEMA_VERSION_KEY)
    if row is None:
        session.add(KeyValue(key=SCHEMA_VERSION_KEY, value={"version": version}))
    else:
        row.value = {"version": version}
    session.flush()


def current_version(db: Database) -> Optional[int]:
    with db.session() as session:
        return _read_version(session)


# ---------------------------------------------------------------------------
# Full-text search table (SQLite only)
# ---------------------------------------------------------------------------

FTS_TABLE = "clip_fts"

#: Contentless-external FTS is tempting but couples the index to rowids, which
#: our string UUID primary keys do not have. A standalone table maintained by
#: the application is simpler and survives clip rewrites.
_FTS_DDL = f"""
CREATE VIRTUAL TABLE IF NOT EXISTS {FTS_TABLE} USING fts5(
    clip_id UNINDEXED,
    title,
    series,
    network,
    summary,
    transcript,
    ocr,
    tags,
    entities,
    tokenize = 'porter unicode61 remove_diacritics 2'
)
"""


def fts_available(db: Database) -> bool:
    """True when this SQLite build has FTS5 compiled in."""
    if not db.is_sqlite:
        return False
    try:
        with db.engine.connect() as conn:
            conn.execute(text("CREATE VIRTUAL TABLE IF NOT EXISTS _fts_probe USING fts5(x)"))
            conn.execute(text("DROP TABLE IF EXISTS _fts_probe"))
            conn.commit()
    except Exception as exc:
        log.warning("FTS5 unavailable; keyword search falls back to LIKE (%s)", exc)
        return False
    return True


def ensure_fts(db: Database) -> bool:
    """Create the FTS table if the build supports it."""
    if not fts_available(db):
        return False
    with db.engine.connect() as conn:
        conn.execute(text(_FTS_DDL))
        conn.commit()
    return True


def drop_fts(db: Database) -> None:
    if not db.is_sqlite:
        return
    with db.engine.connect() as conn:
        conn.execute(text(f"DROP TABLE IF EXISTS {FTS_TABLE}"))
        conn.commit()


def table_counts(db: Database) -> dict[str, int]:
    """Row counts per table, for ``bb status`` and the dashboard."""
    counts: dict[str, int] = {}
    with db.session() as session:
        for table in Base.metadata.sorted_tables:
            try:
                counts[table.name] = int(
                    session.execute(select(text("COUNT(*)")).select_from(table)).scalar_one()
                )
            except Exception:
                counts[table.name] = -1
    return counts
